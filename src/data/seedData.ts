// Generate 125 full FeedbackItems with dates and ids
export function generateSeedFeedback(workspaceId: string): FeedbackItem[] {
  const baseDate = new Date();
  const items: FeedbackItem[] = [];

  // Repeat & adjust to reach 125+ authentic items
  for (let i = 0; i < 125; i++) {
    const raw = RAW_FEEDBACK_ITEMS[i % RAW_FEEDBACK_ITEMS.length];
    const itemDate = new Date(baseDate);
    const dayOffset = (i * 0.25 + (raw.daysAgo || 1)) % 28; // Spread across 4 weeks
    itemDate.setDate(itemDate.getDate() - Math.floor(dayOffset));
    itemDate.setHours(9 + (i % 12), (i * 17) % 60, 0, 0);

    const id = `fb-${workspaceId.replace('ws-', '')}-${String(i + 1).padStart(3, '0')}`;

    items.push({
      id,
      workspaceId,
      title: i >= RAW_FEEDBACK_ITEMS.length ? `${raw.title} (${Math.floor(i / RAW_FEEDBACK_ITEMS.length) + 1})` : raw.title,
      content: raw.content,
      customerName: raw.customerName,
      customerEmail: raw.customerEmail,
      customerCompany: raw.customerCompany,
      customerTier: raw.customerTier,
      channel: raw.channel,
      sentiment: raw.sentiment,
      sentimentScore: raw.sentimentScore,
      status: i % 7 === 0 ? 'ACTIONED' : i % 3 === 0 ? 'REVIEWED' : 'NEW',
      featureArea: raw.featureArea,
      themes: raw.themes,
      tags: raw.tags,
      urgency: raw.urgency,
      createdAt: itemDate.toISOString(),
      aiSummary: `${raw.sentiment === 'NEGATIVE' ? 'Pain point:' : 'Feedback:'} ${raw.content.slice(0, 100)}...`,
      keyQuote: `"${raw.content.slice(0, 110)}..."`,
      actionNotes: i % 7 === 0 ? 'Assigned to Engineering Pod; PR merged in sprint 44.' : undefined,
      actionedBy: i % 7 === 0 ? 'Sarah Jenkins' : undefined,
      actionedAt: i % 7 === 0 ? itemDate.toISOString() : undefined,
    });
  }

  return items;
}

